/**
 * English console strings.
 *
 * Declared `satisfies TranslationShape<typeof zhHant>`, which is the entire
 * safety mechanism: a key present in `zh-Hant.ts` and missing here is a `tsc`
 * error, and so is a stray key that exists only here (excess-property checking
 * on the object literal). Neither can reach production as a silent fallback.
 *
 * `TranslationShape` maps the *structure* of the Chinese resource while typing
 * every leaf as `string`, so the English values are free to differ — which they
 * must, on every single line — while the key set is pinned exactly.
 *
 * Written as **operator English**, not translated Chinese. Where a Hong Kong
 * term has no clean English equivalent the licensed name is kept: a
 * `TAXI_DRIVER_PASS` is the 的士司機證, the document an operator is physically
 * checking, and that is the term used.
 */

