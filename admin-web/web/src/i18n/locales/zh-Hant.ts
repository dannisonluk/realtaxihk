/**
 * Traditional Chinese console strings — the default locale.
 *
 * This file is the **shape contract**: `en.ts` is declared
 * `satisfies typeof zhHant`, so every key added here must be added there too or
 * `tsc` fails. That is deliberate — a missing English translation should break
 * the build, not silently fall back to Chinese at runtime.
 *
 * Grouping is by *surface*, not by string type: `nav`, `prefs`, `common`,
 * `enum` (the server vocabulary shared across pages), then one block per page
 * named after the page. A translator handed this file can work one screen at a
 * time without cross-referencing.
 *
 * Interpolation uses i18next's `{{name}}` syntax. Anything a sentence needs to
 * reorder between languages — a count, a name, a date — must be a placeholder
 * rather than string concatenation, because English and Chinese do not put
 * those in the same place.
 *
 * The object is **not** `as const`: literal value types would make the English
 * file fail to typecheck the moment a translation differed from the Chinese
 * (which is every line). `TranslationShape` in `en.ts` is what enforces key
 * parity while leaving values free.
 */

